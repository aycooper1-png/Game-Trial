import { chromium, devices } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--use-gl=swiftshader'] });
const page = await (await browser.newContext(devices['iPhone 13'])).newPage();
const errs = []; page.on('pageerror', e => errs.push('PAGEERROR ' + e.message));
await page.goto('http://localhost:8765/?seed=42');
await page.waitForFunction(() => !document.getElementById('loading'), null, { timeout: 90000 });
await page.evaluate(() => localStorage.clear()); await page.reload();
await page.waitForFunction(() => !document.getElementById('loading'), null, { timeout: 90000 });
await page.evaluate(() => { window.__game.toggleCmdMenu(true); });
await page.tap('#cmdmenu [data-act="debug"]');
await page.evaluate(() => { const G = window.__game, A = G.activeCountry(); const spotIn = (type, r0 = 3) => { for (let r = r0; r < 14; r++) for (let dx = -r; dx <= r; dx++) for (const dy of [-r, r]) { const i = G.idx(Math.floor(A.lx) + dx, Math.floor(A.ly) + dy); if (!G.canBuild(i, type)) return i; } return -1; };
  G.tryBuild(spotIn('airport', 5), 'airport'); G.tryBuild(spotIn('silo', 7), 'silo'); for (let k = 0; k < 2400; k++) G.tick(0.05); document.querySelectorAll('#notes .note').forEach(n => n.remove()); G.toggleCmdMenu(true); });
await page.waitForTimeout(800);
await page.screenshot({ path: 'mob5-cmd.png' });
await page.evaluate(() => { window.__game.toggleCmdMenu(false); window.__game.toggleBuildMenu(true); });
await page.waitForTimeout(600);
await page.evaluate(() => { const el = [...document.querySelectorAll('.bm-cat')].find(e => e.textContent === 'Space'); if (el) el.scrollIntoView(); });
await page.waitForTimeout(400);
await page.screenshot({ path: 'mob5-build.png' });
console.log(errs.join('\n') || 'no errors');
await browser.close();
