import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--use-gl=swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 1200, height: 800 } });
const page = await ctx.newPage();
const errs = []; page.on('pageerror', e => errs.push(e.message));
await page.goto('http://localhost:8765/?seed=9&tr=bc');
await page.waitForFunction(() => !document.getElementById('loading'), null, { timeout: 60000 });
await page.evaluate(() => (0, eval)('askNewGame()'));
await page.screenshot({ path: '/tmp/ui_new.png' });
await page.click('.mode-btn.mp');
await page.click('[data-style="coop"]');
await page.screenshot({ path: '/tmp/ui_setup.png' });
await Promise.all([page.waitForNavigation(), page.click('#md-btns button.go')]);
await page.waitForFunction(() => !document.getElementById('loading'), null, { timeout: 60000 });
console.log(page.url());
await page.waitForTimeout(500);
await page.screenshot({ path: '/tmp/ui_wait.png' });
console.log(errs.join('\n') || 'no errors');
await browser.close();
