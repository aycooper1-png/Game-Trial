import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--use-gl=swiftshader'] });
const page = await (await browser.newContext({ viewport: { width: 1300, height: 820 } })).newPage();
const errs = []; page.on('pageerror', e => errs.push(e.message + '\n' + e.stack));
page.on('console', m => { if (m.type() === 'error') errs.push('console ' + m.text()); });
await page.goto('http://localhost:8765/?seed=42');
await page.waitForFunction(() => !document.getElementById('loading'), null, { timeout: 60000 });
await page.evaluate(() => { localStorage.clear(); const G = window.__game; G.completeTech('masonry', true); G.toggleBuildMenu(true); });
await page.waitForTimeout(500);
const card = (await page.$$('.bm-card')).length ? await page.evaluateHandle(() => [...document.querySelectorAll('.bm-card')].find(e => e.querySelector('.bm-name').textContent === 'Bridge')) : null;
console.log('card found', !!card, await page.evaluate(() => { const e = document.querySelector('[data-type="bridge"]'); return e ? e.outerHTML.slice(0, 300) : [...document.querySelectorAll('.bm-card')].find(e => e.querySelector('.bm-name').textContent === 'Bridge')?.querySelector('.tile').innerHTML; }));
const t0 = Date.now();
if (card) await card.asElement().click();
await page.waitForTimeout(300);
const r = await page.evaluate(() => { const a = performance.now(); return new Promise(res => requestAnimationFrame(() => requestAnimationFrame(() => res(performance.now() - a)))); });
console.log('two frames ms', Math.round(r), 'click->now', Date.now() - t0, 'ghost', await page.evaluate(() => JSON.stringify(window.__game.game.ghost)));
await page.mouse.move(650, 400); await page.waitForTimeout(500);
const r2 = await page.evaluate(() => { const a = performance.now(); return new Promise(res => requestAnimationFrame(() => requestAnimationFrame(() => res(performance.now() - a)))); });
console.log('frames after move', Math.round(r2));
await page.screenshot({ path: 'br1.png' });
console.log(errs.join('\n') || 'no errors');
await browser.close();
